func TestRenderDeployDoc(t *testing.T) {
	file, err := common.RenderDeployDoc(webPlan())
	require.NoError(t, err)
	require.Equal(t, "DEPLOY.md", file.Path)
	doc := string(file.Content)
	for _, want := range []string{
		"docker compose up -d --build",
		"cp -n .env.example .env",
		"Caddy",
		"reverse_proxy localhost:3000",
		"postgres_data",
		"pg_dump",
	} {
		require.Contains(t, doc, want)
	}

	worker := webPlan()
	worker.Process, worker.Services = plan.ProcessWorker, []plan.Service{plan.ServiceMongo}
	file, err = common.RenderDeployDoc(worker)
	require.NoError(t, err)
	doc = string(file.Content)
	require.Contains(t, doc, "unless-stopped")
	require.Contains(t, doc, "mongo_data")
	require.Contains(t, doc, "mongodump")

	unknown := webPlan()
	unknown.Process, unknown.Services = "cron", []plan.Service{"kafka"}
	file, err = common.RenderDeployDoc(unknown)
	require.NoError(t, err)
	doc = string(file.Content)
	require.Contains(t, doc, `TODO: process type "cron"`)
	require.Contains(t, doc, "kafka")
	require.Contains(t, doc, "TODO")
}

func TestRenderersDoNotMutatePlan(t *testing.T) {
	p := webPlan()
	before := fmt.Sprintf("%v", p)
	for _, render := range []func(plan.Plan) (emit.File, error){
		common.RenderCompose, common.RenderAction, common.RenderDeployDoc,
	} {
		_, err := render(p)
		require.NoError(t, err)
	}
	require.Equal(t, before, fmt.Sprintf("%v", p))
}
